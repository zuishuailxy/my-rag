-- 文档分片向量表（PGVector）：发布后由 RAG 消费者写入，支撑语义检索
-- 对齐已实现的 kh_document 模型（document_id → kh_document.id，级联删除）
-- 对应 TS VectorIndexService 的 ES kh_chunk（字段含 dense_vector），此处落 PG
CREATE EXTENSION IF NOT EXISTS vector;   -- pgvector 扩展

CREATE TABLE IF NOT EXISTS doc_chunk (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id    BIGINT      NOT NULL REFERENCES kh_document(id) ON DELETE CASCADE,
    chunk_id       VARCHAR(64) UNIQUE,                    -- sha256(documentId:index)，upsert 主键
    chunk_index    INT         NOT NULL,                  -- 分片序号（0 起）
    content        TEXT        NOT NULL,                  -- 分片文本
    heading        VARCHAR(255),                          -- 所属章节标题（检索展示）
    document_title VARCHAR(255),                          -- 文档标题（检索展示）
    total_chunks   INT,                                   -- 总块数（检索展示）
    category_id    BIGINT,                                -- 冗余分类（与 kh_document 一致，便于检索过滤）
    author_id      BIGINT,
    team_id        BIGINT,
    doc_status     SMALLINT,                              -- 文档状态快照（0/1/2）
    publish_time   TIMESTAMP,                             -- 发布时间快照
    embedding      vector(1024) NOT NULL,                 -- 文本向量（对齐架构 1024 维；对应 ES dense_vector）
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),    -- 对应 ES indexed_at
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 按文档查询/重建
CREATE INDEX IF NOT EXISTS idx_doc_chunk_document ON doc_chunk(document_id);
-- 向量检索（余弦相似度，HNSW）
CREATE INDEX IF NOT EXISTS idx_doc_chunk_embedding
    ON doc_chunk USING hnsw (embedding vector_cosine_ops);
