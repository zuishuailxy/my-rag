-- ============================================================
-- PostgreSQL 数据库表结构（DDL）
-- 企业智能知识库系统 my-rag
-- 依赖镜像：pgvector/pgvector:pg16（自带 vector 扩展）
-- 执行方式：由 docker-entrypoint-initdb.d 在首次启动时自动执行
-- ============================================================

CREATE EXTENSION IF NOT EXISTS vector;        -- PGVector 向量检索
CREATE EXTENSION IF NOT EXISTS pg_trgm;       -- 三元组模糊匹配（文件名搜索）

-- ------------------------------------------------------------
-- 1. RBAC 权限域
-- ------------------------------------------------------------

-- 部门表（支持上下级组织树）
CREATE TABLE department (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(100) NOT NULL,                 -- 部门名称
    parent_id       BIGINT REFERENCES department(id),      -- 上级部门（NULL 为根）
    sort_order      INT          NOT NULL DEFAULT 0,       -- 同级排序
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- 用户表
CREATE TABLE "user" (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR(50)  NOT NULL UNIQUE,          -- 登录账号
    password_hash   VARCHAR(255) NOT NULL,                 -- bcrypt 密码哈希
    nickname        VARCHAR(50),                           -- 显示昵称
    email           VARCHAR(120),
    phone           VARCHAR(30),
    avatar_url      VARCHAR(500),                          -- 头像（RustFS 资源 URL）
    department_id   BIGINT REFERENCES department(id),      -- 所属部门
    status          SMALLINT     NOT NULL DEFAULT 1,       -- 1 启用 / 0 禁用
    last_login_at   TIMESTAMPTZ,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- 角色表
CREATE TABLE role (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(50)  NOT NULL UNIQUE,          -- 角色编码（如 admin / dept_leader）
    name            VARCHAR(100) NOT NULL,                 -- 角色名称
    description     VARCHAR(255),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- 权限表（页面级 / 菜单级 / 按钮级功能权限）
CREATE TABLE permission (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(100) NOT NULL UNIQUE,          -- 权限编码（如 doc:upload）
    name            VARCHAR(100) NOT NULL,                 -- 权限名称
    type            VARCHAR(20)  NOT NULL,                 -- menu 菜单 / button 按钮 / api 接口
    parent_id       BIGINT REFERENCES permission(id),      -- 权限树
    path            VARCHAR(255),                          -- 前端路由或接口路径
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- 用户-角色关联
CREATE TABLE user_role (
    user_id         BIGINT NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
    role_id         BIGINT NOT NULL REFERENCES role(id)    ON DELETE CASCADE,
    PRIMARY KEY (user_id, role_id)
);

-- 角色-权限关联
CREATE TABLE role_permission (
    role_id         BIGINT NOT NULL REFERENCES role(id)       ON DELETE CASCADE,
    permission_id   BIGINT NOT NULL REFERENCES permission(id) ON DELETE CASCADE,
    PRIMARY KEY (role_id, permission_id)
);

-- ------------------------------------------------------------
-- 2. 文档与分片域
-- ------------------------------------------------------------

-- 文件夹表（文档目录树）
CREATE TABLE folder (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(200) NOT NULL,
    parent_id       BIGINT REFERENCES folder(id),          -- 上级文件夹（NULL 为根）
    owner_id        BIGINT REFERENCES "user"(id),          -- 创建人
    visibility      VARCHAR(20)  NOT NULL DEFAULT 'private', -- private 仅本人 / department 部门 / company 公司 / public 公开
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- 文档表
CREATE TABLE document (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(300) NOT NULL,                 -- 文档名称
    file_type       VARCHAR(20)  NOT NULL,                 -- pdf/docx/xlsx/pptx/txt/md/csv/json/jpg/png/mp3/wav/m4a/mp4/url
    mime_type       VARCHAR(100),
    file_size       BIGINT       NOT NULL DEFAULT 0,       -- 字节
    category        VARCHAR(50),                           -- 业务分类（产品文档/技术文档/培训资料/制度流程/市场营销）
    folder_id       BIGINT REFERENCES folder(id),          -- 所属文件夹
    owner_id        BIGINT NOT NULL REFERENCES "user"(id), -- 上传人
    visibility      VARCHAR(20)  NOT NULL DEFAULT 'private', -- private / department / company / public
    source_type     VARCHAR(20)  NOT NULL DEFAULT 'upload',  -- upload 文件上传 / url 网页抓取
    source_url      VARCHAR(1000),                         -- 网页 URL（source_type=url 时）
    rustfs_key      VARCHAR(500),                          -- 原始文件在 RustFS 的对象键
    content_md      TEXT,                                  -- 解析后的 Markdown 原文（内嵌资源为 RustFS URL）
    content_hash    VARCHAR(64),                           -- 内容哈希，用于去重/增量更新
    parse_status    VARCHAR(20)  NOT NULL DEFAULT 'pending', -- pending 待处理 / parsing 解析中 / done 完成 / failed 失败
    parse_error     TEXT,                                  -- 失败原因
    chunk_count     INT          NOT NULL DEFAULT 0,       -- 分片数量
    status          SMALLINT     NOT NULL DEFAULT 1,       -- 1 正常 / 0 已删除（软删除）
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX idx_document_folder    ON document(folder_id);
CREATE INDEX idx_document_owner     ON document(owner_id);
CREATE INDEX idx_document_status    ON document(parse_status);
CREATE INDEX idx_document_name_trgm ON document USING gin (name gin_trgm_ops);

-- 文档分片表（向量字段走 PGVector；维度 1024 按嵌入模型调整）
CREATE TABLE doc_chunk (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id     BIGINT NOT NULL REFERENCES document(id) ON DELETE CASCADE,
    chunk_index     INT    NOT NULL,                       -- 分片在文档内的序号
    content         TEXT   NOT NULL,                       -- 分片文本
    token_count     INT,                                   -- Token 数（成本/截断统计）
    embedding       vector(1024),                          -- 文本向量
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_chunk_document ON doc_chunk(document_id);
-- HNSW 向量索引，余弦距离
CREATE INDEX idx_chunk_embedding ON doc_chunk
    USING hnsw (embedding vector_cosine_ops);

-- 多模态向量表（图片/音频/视频特征向量，支撑以图搜图与跨模态检索）
CREATE TABLE media_vector (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id     BIGINT NOT NULL REFERENCES document(id) ON DELETE CASCADE,
    media_type      VARCHAR(20) NOT NULL,                  -- image / audio / video
    rustfs_key      VARCHAR(500),                          -- 媒体资源对象键（图片/帧图/音频轨）
    embedding       vector(1024),                          -- 多模态特征向量（与文本向量同空间才可跨模态）
    meta            JSONB,                                 -- 附加信息（帧时间戳、时长等）
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_media_document ON media_vector(document_id);
CREATE INDEX idx_media_embedding ON media_vector
    USING hnsw (embedding vector_cosine_ops);

-- 解析任务表（前端轮询解析进度）
CREATE TABLE document_task (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id     BIGINT REFERENCES document(id) ON DELETE CASCADE,
    task_type       VARCHAR(30)  NOT NULL,                 -- parse 解析 / reindex 重建索引 / graph 图谱抽取
    status          VARCHAR(20)  NOT NULL DEFAULT 'pending', -- pending / running / done / failed
    step            VARCHAR(50),                           -- 当前步骤（rustfs_upload / parse / chunk / vectorize / es_index / graph_extract）
    progress        SMALLINT     NOT NULL DEFAULT 0,       -- 0~100
    error_message   TEXT,
    retry_count     SMALLINT     NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    started_at      TIMESTAMPTZ,
    finished_at     TIMESTAMPTZ
);

CREATE INDEX idx_task_document ON document_task(document_id);
CREATE INDEX idx_task_status   ON document_task(status);

-- 文档权限明细（在 visibility 基础上的精细授权：指定角色/部门/用户可见）
CREATE TABLE document_permission (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id     BIGINT NOT NULL REFERENCES document(id) ON DELETE CASCADE,
    target_type     VARCHAR(20) NOT NULL,                  -- user / role / department
    target_id       BIGINT      NOT NULL,                  -- 对应表主键
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (document_id, target_type, target_id)
);

-- 操作日志（首页大盘"近期操作记录"）
CREATE TABLE operation_log (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT REFERENCES "user"(id),
    action          VARCHAR(50)  NOT NULL,                 -- upload 上传 / update / delete / login / chat 问答 / search
    content         VARCHAR(500),                          -- 操作内容描述
    document_id     BIGINT REFERENCES document(id),
    ip              VARCHAR(45),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX idx_oplog_time ON operation_log(created_at DESC);

-- ------------------------------------------------------------
-- 3. AI 问答域
-- ------------------------------------------------------------

-- 对话会话表
CREATE TABLE chat_session (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
    title           VARCHAR(200),                          -- 会话标题（默认取首问摘要）
    last_message_at TIMESTAMPTZ,
    message_count   INT NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_session_user ON chat_session(user_id, last_message_at DESC);

-- 问答消息记录表
CREATE TABLE chat_message (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id      BIGINT NOT NULL REFERENCES chat_session(id) ON DELETE CASCADE,
    role            VARCHAR(20) NOT NULL,                  -- user / assistant / system
    content         TEXT        NOT NULL,                  -- 消息内容
    citations       JSONB,                                 -- 引用文档 [{document_id, chunk_id, title, score}]
    reasoning_meta  JSONB,                                 -- Agent 元信息（路由分支、召回耗时、Token 消耗、trace_id）
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_message_session ON chat_message(session_id, created_at);

-- ------------------------------------------------------------
-- 4. 更新触发器：自动维护 updated_at
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION touch_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DO $$
DECLARE t TEXT;
BEGIN
    FOR t IN
        SELECT unnest(ARRAY['department','"user"','role','folder','document',
                            'chat_session'])
    LOOP
        EXECUTE format(
            'CREATE TRIGGER trg_%s_touch BEFORE UPDATE ON %s
             FOR EACH ROW EXECUTE FUNCTION touch_updated_at();',
            replace(t, '"', ''), t);
    END LOOP;
END $$;

